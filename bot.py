def send_test_question(chat_id):
    """Отправить вопрос теста"""
    data = user_test_answers.get(chat_id)
    if not data:
        return
    
    q_num = data["current"]
    if q_num >= len(ADAPTATION_TEST):
        finish_test(chat_id)
        return
    
    question = ADAPTATION_TEST[q_num]
    buttons = [[{"text": opt}] for opt in question["options"]]
    buttons.append([{"text": "🚫 Прервать тест"}])
    
    keyboard = {"keyboard": buttons, "resize_keyboard": True}
    send_message(chat_id, f"📋 <b>Вопрос {q_num + 1} из {len(ADAPTATION_TEST)}</b>\n\n{question['q']}", keyboard)

def process_test_answer(chat_id, answer):
    """Обработка ответа на тест"""
    data = user_test_answers.get(chat_id)
    if not data:
        return
    
    q_num = data["current"]
    question = ADAPTATION_TEST[q_num]
    
    # Сохраняем ответ
    data["answers"].append(answer)
    if answer in question["dangerous"]:
        data["dangerous_count"] += 1
    
    # Показываем пояснение
    send_message(chat_id, f"📝 <i>{question['explanation']}</i>")
    
    # Переходим к следующему вопросу
    data["current"] += 1
    send_test_question(chat_id)

def finish_test(chat_id):
    """Завершение теста"""
    data = user_test_answers.get(chat_id)
    if not data:
        return
    
    dangerous = data["dangerous_count"]
    
    if dangerous >= 7:
        result = "🔴 <b>Высокий риск выгорания</b>\n\nТебе нужна пауза. Возьми 2-3 выходных. Выбери 3 техники из блоков «Выгорание» или «Энергия смены» и выполняй их ежедневно 2 недели."
    elif dangerous >= 4:
        result = "🟡 <b>Зона риска</b>\n\nТы держишься, но ресурс на исходе. Внедри ритуал восстановления (блок «Энергия смены») и приём из «Я и коллектив сейчас». Через месяц пройди тест снова."
    else:
        result = "🟢 <b>Хороший ресурс</b>\n\nТы управляешь своим состоянием. Поделись с коллегой, который выглядит уставшим. Иногда фраза «ты как?» может изменить день человека."
    
    buttons = ["🏠 В главное меню", "◀️ В меню адаптации"]
    send_keyboard(chat_id, f"✅ <b>Тест пройден!</b>\n\nТревожных ответов: {dangerous} из {len(ADAPTATION_TEST)}\n\n{result}", buttons)
    
    del user_test_answers[chat_id]

